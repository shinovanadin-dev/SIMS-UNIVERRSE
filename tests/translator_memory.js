const fs=require("fs"),vm=require("vm"),assert=require("assert");
const html=fs.readFileSync("index.html","utf8");
const start=html.indexOf('const TRANSLATOR_MEMORY_KEY="simsUniverseTranslationMemoryV1";');
const end=html.indexOf("async function translatorAITranslateUntranslated(){",start);
assert(start>=0&&end>start,"translation memory helpers found");
const code=html.slice(start,end);
const store=new Map();
const sandbox={localStorage:{getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,v)},JSON, String, Object};
vm.runInNewContext(code,sandbox);
const key=sandbox.translatorMemoryKey("Russian"," Hello ");
assert.strictEqual(key,"russian|Hello","key normalizes language/source whitespace");
assert.strictEqual(sandbox.translatorMemoryGet("Russian","Hello"),null,"cache miss");
assert.strictEqual(sandbox.translatorMemorySet("Russian","Hello","Привет"),true,"store entry");
assert.strictEqual(sandbox.translatorMemoryGet("Russian"," Hello "),"Привет","trimmed lookup");
assert.strictEqual(sandbox.translatorMemoryGet("russian","Hello"),"Привет","language case normalized");
assert.strictEqual(sandbox.translatorMemoryStats(),1,"stats count");
sandbox.translatorMemorySet("Russian","Hello","Здравствуйте");
assert.strictEqual(sandbox.translatorMemoryGet("Russian","Hello"),"Здравствуйте","update existing entry");
assert.strictEqual(sandbox.translatorMemorySet("Russian","","empty"),false,"reject empty source");
assert.strictEqual(sandbox.translatorMemorySet("Russian","nonempty",""),false,"reject empty translation");
let db={};for(let i=0;i<3005;i++)db["k"+i]="v"+i;store.set("simsUniverseTranslationMemoryV1",JSON.stringify(db));
sandbox.translatorMemorySet("Russian","new key","new value");
let trimmed=JSON.parse(store.get("simsUniverseTranslationMemoryV1"));
assert.strictEqual(Object.keys(trimmed).length,3000,"caps persistent memory at 3000 entries");
assert.strictEqual(trimmed.k0,undefined,"oldest entries trimmed");
assert.strictEqual(trimmed["k3004"],"v3004","recent entries retained");
assert.strictEqual(trimmed["russian|new key"],"new value","new value stored after trimming");
store.set("simsUniverseTranslationMemoryV1","not json");
assert.strictEqual(sandbox.translatorMemoryStats(),0,"corrupt storage safely reports empty");
assert.strictEqual(sandbox.translatorMemoryGet("Russian","Hello"),null,"corrupt storage safely returns cache miss");
console.log("Translation memory regression: 12 checks passed");
